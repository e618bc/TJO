"""Банк вопросов к ИИ.

Код находит в вакансии кандидатов и решает, какие вопросы вообще имеют смысл; ИИ отвечает,
выбирая один вариант из закрытого списка. У каждого вопроса есть вариант «unclear»:
неясный ответ замечания не создаёт. Вопрос задаётся, только если его ответ может изменить отчёт.
"""
from __future__ import annotations

import re
from dataclasses import dataclass

from .facts import Facts
from .facts import stem as F_stem

UNCLEAR = "unclear"


@dataclass
class Question:
    id: str
    text: str
    options: list            # пары (идентификатор, пояснение)

    @property
    def option_ids(self) -> list:
        return [o for o, _ in self.options] + [UNCLEAR]


def _refs(cands, limit=4) -> str:
    """Номера фрагментов-кандидатов в виде «[3], [7]»."""
    seen = []
    for c in cands:
        if c.sent.n not in seen:
            seen.append(c.sent.n)
    return ", ".join("название должности" if n == 0 else f"[{n}]" for n in seen[:limit])


def build_questions(f: Facts) -> list[Question]:
    q: list[Question] = []
    has_text = bool(f.sentences)
    text_low = f.free_text.lower()

    if has_text:
        q.append(Question("duties", "Насколько конкретно во всей вакансии описано, что должен делать работник?", [
            ("concrete", "названа хотя бы одна конкретная задача: действие и его объект («приём пациентов», «уборка двора»)"),
            ("general", "только общие слова без конкретных задач («работа с документами», «другие задачи по необходимости»)"),
            ("boss", "только поручения руководителя"),
            ("ref", "только отсылка к должностной инструкции или договору"),
            ("traits", "вместо задач — личные качества или требования к кандидату"),
            ("promo", "вместо задач — реклама работодателя, льготы, условия"),
            ("title", "задач нет, текст лишь повторяет название должности"),
        ]))
    if f.title.strip():
        q.append(Question("title_kind", f"Что сообщает название вакансии «{f.title.strip()[:120]}»?", [
            ("prof", "конкретную профессию или должность, род работы понятен"),
            ("generic", "общее слово без рода работы (специалист, сотрудник, работник, менеджер)"),
            ("multi", "несколько разных профессий сразу"),
        ]))
        if has_text:
            q.append(Question("title_match", "Название должности и описанные обязанности относятся к одной и той же работе?", [
                ("same", "да, или обязанности — смежные функции этой должности"),
                ("diff", "нет, обязанности описывают другую профессию или другой предмет работы"),
                ("vague", "обязанности слишком общие, чтобы судить"),
            ]))
        if re.search(r",|/|\sи\s", f.title) and not re.search(r"\(.*[,/].*\)", f.title):
            q.append(Question("title_cover", "В названии несколько должностей. Обязанности описывают их все?", [
                ("all", "да, все"),
                ("part", "нет, только часть из них"),
                ("one", "это одна должность (двойное название или мужской и женский род)"),
            ]))

    edu_in_text = bool(re.search(r"образовани|диплом|высше|средне\w*\s+(проф|спец)", text_low))
    if has_text and (f.education == "empty" or edu_in_text):
        q.append(Question("edu_text", "Какое образование требуется от кандидата по тексту вакансии (справочное поле не учитывай)?", [
            ("none", "в тексте об образовании кандидата ничего не сказано"),
            ("train", "образование не названо, но сказано, что работодатель обучает"),
            ("notreq", "прямо сказано, что образование не требуется"),
            ("school", "общее среднее (школа)"),
            ("spo", "среднее профессиональное или среднее специальное"),
            ("high", "высшее"),
            ("or", "несколько УРОВНЕЙ на выбор («среднее профессиональное или высшее»); если «или» стоит между "
                   "специальностями одного уровня, выбирай сам этот уровень"),
            ("wish", "образование названо только как пожелание или преимущество"),
            ("subject", "слово «образование» относится к предмету работы, а не к кандидату"),
        ]))

    exp = f.of("exp")
    if exp:
        q.append(Question("exp_text", f"Что говорят об опыте работы кандидата фрагменты {_refs(exp)}? Суди только по тексту, "
                                      "справочное поле «Опыт» не учитывай.", [
            ("notreq", "опыт не требуется, можно без опыта"),
            ("wish", "опыт желателен, приветствуется, будет преимуществом"),
            ("req_nodur", "опыт обязателен, срок не назван"),
            ("lt1", "обязателен опыт меньше года (несколько месяцев)"),
            ("y1_2", "обязателен опыт от 1 до 2 лет"),
            ("y3plus", "обязателен опыт 3 года и больше"),
            ("other", "речь о другом стаже (водительский, общий) или об опыте компании"),
            ("none", "об опыте кандидата ничего не сказано"),
        ]))

    pay = f.of("pay")
    if f.salary_min == 0 and f.salary_max == 0 and has_text:
        q.append(Question("pay_named", "Названа ли в тексте вакансии числом сумма оплаты труда?", [
            ("yes", "да, есть сумма зарплаты, оклада или дохода"),
            ("no", "нет, суммы оплаты в тексте нет"),
        ]))
    if pay and (f.salary_min or f.salary_max):
        hi = f.salary_max if f.salary_max else "не задано"
        q.append(Question(
            "pay_consistency",
            f"В полях зарплата от {f.salary_min} до {hi} рублей в месяц. Суммы в тексте (фрагменты {_refs(pay)}) "
            "согласуются с этими значениями?", [
                ("consistent", "да; в том числе если это оклад или премия как часть заработка, сумма на испытательный "
                               "срок, сумма «на руки» или ставка за час и смену"),
                ("conflict", "нет, в тексте назван другой размер месячного заработка"),
                ("notpay", "числа в этих фрагментах не являются оплатой труда"),
            ]))
    ceiling = max([f.salary_max] + [c.value for c in pay if c.info["bound"] == "to"])
    distinct = sorted({c.value for c in pay if c.info["bound"] != "to"})
    if len({c.sent.n for c in pay}) >= 2 and len(distinct) >= 2 and distinct[-1] > distinct[0] * 1.05:
        q.append(Question("pay_texts", f"Суммы оплаты во фрагментах {_refs(pay)} согласуются между собой?", [
            ("consistent", "да: это части одного заработка (оклад и итог), разные периоды или сумма на руки"),
            ("conflict", "нет: для одной и той же оплаты названы разные суммы"),
            ("notpay", "это не суммы оплаты труда"),
        ]))
    if f.salary_min and ceiling >= 2 * f.salary_min and has_text:
        q.append(Question("pay_explained", "Объясняет ли текст, от чего зависит размер заработка (категория, нагрузка, "
                                           "выработка, процент, стаж, число ставок)?", [("yes", "да"), ("no", "нет")]))

    sched = f.of("schedule")
    field_regime = f.schedule.regime
    if not f.schedule.has_params and field_regime not in ("full", "day5", "irregular"):
        q.append(Question("days_named", "Названы ли где-либо в вакансии рабочие дни или чередование рабочих и выходных "
                                        "(5/2, 2/2, пн–пт, сутки через трое, длительность вахты)?",
                          [("yes", "да"), ("no", "нет")]))
        q.append(Question("hours_named", "Названы ли где-либо в вакансии часы работы: время начала и окончания или "
                                         "длительность смены?", [("yes", "да"), ("no", "нет")]))
    if sched and (f.schedule_raw.strip() or len(sched) >= 2):
        field_part = f"В поле графика указано «{f.schedule_raw.strip()[:120]}». " if f.schedule_raw.strip() else ""
        q.append(Question(
            "sch_consistency",
            f"{field_part}О графике также говорят фрагменты {_refs(sched)}. Как эти сведения соотносятся?", [
                ("one", "это один режим работы, сведения дополняют или уточняют друг друга"),
                ("conflict", "названы разные режимы работы для этой должности, и не объяснено, какой действует"),
                ("options", "прямо предложены варианты на выбор работника или режимы для разных периодов"),
                ("notschedule", "фрагменты не о графике работника (предмет работы, часы работы организации, отрицание)"),
            ]))

    part = f.of("part")
    emp_low = f.employment.lower()
    if part or f.schedule.part or "частичн" in emp_low:
        q.append(Question("volume_text", "Какой объём занятости следует из текста вакансии?", [
            ("full", "полный день или полная ставка, в том числе обычная норма профессии (например, 18 часов учителя)"),
            ("part_sized", "неполный, и названы часы или доля ставки"),
            ("part", "неполный или подработка, размер не назван"),
            ("none", "об объёме занятости в тексте ничего не сказано"),
        ]))

    remote, onsite = f.of("remote"), f.of("onsite")
    if remote or onsite or re.search(r"дистанц|удал[её]н", emp_low):
        q.append(Question("format", "Что вакансия говорит о формате работы: на месте или дистанционно?", [
            ("onsite", "работа на месте, в офисе или на объекте"),
            ("remote", "работа дистанционная"),
            ("mixed", "совмещение, и понятно, как оно устроено"),
            ("conflict", "в одном месте сказано «дистанционно», в другом — обязательное присутствие, без объяснения"),
            ("none", "о формате ничего не сказано"),
        ]))

    if len({F_stem(n) for n in f.address_settlements}) >= 2:
        q.append(Question("multi_place", "В вакансии указано несколько адресов в разных населённых пунктах. Сказано ли, "
                                         "где основное место работы и как работа распределяется между адресами?", [
            ("explained", "да, сказано"), ("not_explained", "нет, не сказано"),
        ]))
    if not f.address_settlements and has_text:
        q.append(Question("place_named", "Назван ли где-либо в вакансии город, посёлок или село, где нужно работать? "
                                         "Область и район без населённого пункта не считаются.",
                          [("yes", "да, назван конкретный город, посёлок или село"),
                           ("no", "нет, есть только область или район либо места нет совсем")]))
    other = [c for c in f.of("settlement") if not c.info["same"]]
    if other and f.address_settlements:
        names = ", ".join(dict.fromkeys(c.value for c in other))
        q.append(Question(
            "place_conflict",
            f"В адресе указан населённый пункт «{f.address_settlements[0]}». В вакансии также упомянут «{names}» "
            f"(фрагменты {_refs(other) or 'название должности'}). Что это за упоминание?", [
                ("work", "здесь работник будет постоянно работать (в том числе учреждение или объект в этом "
                         "населённом пункте)"),
                ("trip", "выезды, командировки или зона обслуживания"),
                ("transport", "маршрут служебного транспорта или место жительства кандидата"),
                ("other", "адрес головной организации, место собеседования или иное, но не место работы"),
            ]))

    unit = f.of("unit")
    if unit:
        q.append(Question("pay_basis", f"Фрагменты {_refs(unit)} говорят о почасовой, сменной, сдельной или процентной "
                                       "оплате. Названа ли в вакансии ставка или расценка?", [
            ("rate_named", "да, названа ставка за час, смену, единицу работы или процент"),
            ("rate_missing", "нет, сказано только, что оплата почасовая, сменная, сдельная или процентная"),
            ("not_pay", "фрагменты не об оплате труда"),
        ]))
    temp = f.of("temp")
    if temp:
        q.append(Question("term_kind", f"Судя по фрагментам {_refs(temp)}, работа по вакансии постоянная или на "
                                       "ограниченный срок?", [
            ("temporary", "на ограниченный срок: сезон, период, срочный договор, замещение"),
            ("permanent", "постоянная; срок относится к чему-то другому (испытательный срок, обучение, график)"),
        ]))
    extra = f.of("extra")
    if extra:
        q.append(Question("extra_time", f"Фрагменты {_refs(extra)} говорят о работе вне основного графика. "
                                        "Описано ли, как часто это бывает и на каких условиях?", [
            ("described", "да, названы частота или порядок и условия (оплата, отгулы)"),
            ("not_described", "нет, сказано только, что такая работа возможна или бывает"),
            ("not_extra", "фрагменты не о работе вне графика"),
        ]))
    for i, c in enumerate(f.of("req_pair")[:2], 1):
        q.append(Question(f"req_pair_{i}", f"Сравни фрагменты [{c.sent.n}] и [{c.value.n}]. Они противоречат друг "
                                           "другу в требованиях к кандидату?", [
            ("conflict", "да: в одном это обязательно, в другом не требуется"),
            ("consistent", "нет, они согласуются или говорят о разном"),
        ]))
    for i, c in enumerate(f.of("reference")[:2], 1):
        q.append(Question(f"ref_{i}", f"Фрагмент [{c.sent.n}] откладывает сведения на потом («на собеседовании», "
                                      "«по договорённости»). Какие сведения он откладывает?", [
            ("pay", "размер оплаты"),
            ("schedule", "график работы"),
            ("place", "место, адрес или формат работы"),
            ("duties", "обязанности"),
            ("requirements", "требования к кандидату"),
            ("all", "условия в целом, без уточнения"),
            ("notref", "это не отсылка: сведения названы или фраза о другом"),
        ]))
    return q


FIELD_TITLES = {
    "duty": "обязанности", "requirements": "требования", "requirement.qualification": "квалификация",
    "qualification": "квалификация", "schedule": "график", "scheduleTypeComment": "комментарий к графику",
    "term.text": "условия", "benefitDetails": "льготы", "skills": "навыки",
}


def render_state(f: Facts, max_sentences: int = 70, max_len: int = 320) -> str:
    """Вакансия в виде, удобном для модели: поля-справочники и пронумерованные фрагменты текста."""
    hi = f.salary_max if f.salary_max else "не задано"
    lines = [
        f"Название должности: {f.title.strip() or 'не указано'}",
        f"Зарплата в полях: от {f.salary_min} до {hi}",
        f"График (поле): {f.schedule_raw.strip() or 'не указан'}"
        + (f"; смены: {', '.join(f.shift_values)}" if f.shift_values else ""),
        f"Занятость (поле): {f.employment.strip() or 'не указана'}",
        f"Образование (поле): {f.education_raw.strip() or 'не указано'}",
        f"Опыт в годах (поле): {f.experience if f.experience_present else 'не указан'}",
        f"Адрес (поле): {'; '.join(f.addresses) or 'не указан'}",
        "",
        "Фрагменты текста вакансии:",
    ]
    for s in f.sentences[:max_sentences]:
        label = FIELD_TITLES.get(s.field, s.field)
        lines.append(f"[{s.n}] ({label}) {s.text[:max_len]}")
    if not f.sentences:
        lines.append("(текста нет)")
    return "\n".join(lines)
